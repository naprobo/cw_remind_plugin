export function resolveLocale(locale?: string): SupportedLocale {
  const normalized = (locale || '').replace('_', '-').toLowerCase();
  if (normalized === 'ja' || normalized.startsWith('ja-')) { return 'ja'; }
  if (normalized === 'zh-cn' || normalized === 'zh-hans' || normalized.startsWith('zh-hans-')) { return 'zh-CN'; }
  return 'en';
}

export function getMessages(locale: SupportedLocale): Messages {
  return messages[locale];
}

const serverErrorKeys: Record<string, keyof Messages> = {
  '提醒标题必须为 1–200 字符': 'titleInvalid',
  '提醒内容必须为 1–4000 字符': 'contentInvalid',
  '频道不能为空': 'channelRequired',
  '你不是该频道成员': 'notChannelMember',
  '提醒对象无效': 'audienceInvalid',
  '无法读取建立者': 'creatorUnavailable',
  '时区无效': 'timezoneInvalid',
  '期限日期无效': 'dueDateInvalid',
  '提醒规则必须为 1–50 组': 'rulesCountInvalid',
  '提前天数必须在 0–3650 之间': 'daysBeforeInvalid',
  '提醒时间无效': 'timeInvalid',
  '提醒规则重复': 'ruleDuplicate',
  '提醒时点已过期': 'reminderExpired',
  '请至少指定一个用户': 'userRequired',
};

export function localizeServerError(message: string, locale: SupportedLocale): string {
  const text = messages[locale];
  const key = serverErrorKeys[message];
  if (key) { return text[key]; }
  const missingUser = message.match(/^用户 @(.+) 不存在$/);
  if (missingUser) { return text.userNotFound.replace('{username}', missingUser[1]); }
  const userOutsideChannel = message.match(/^用户 @(.+) 不是该频道成员$/);
  if (userOutsideChannel) { return text.userNotInChannel.replace('{username}', userOutsideChannel[1]); }
  return message;
}
